import uuid
from pathlib import Path

try:
    import openpyxl
except ImportError:
    sys.exit("❌  openpyxl not installed. Run:  pip install openpyxl")

EXCEL_FILE = "3 time silly topic update.xlsx"

# ─── Load workbook ─────────────────────────────────────────────────────────────
def load_wb():
    p = Path(EXCEL_FILE)
    if not p.exists():
        sys.exit(f"❌  '{EXCEL_FILE}' not found. Place it in the same folder as this script.")
    return openpyxl.load_workbook(p, data_only=True)

# ─── Read Common Config ────────────────────────────────────────────────────────
def read_common(wb):
    ws = wb["⚙ Common Config"]
    cfg = {}
    for row in ws.iter_rows(min_row=3, values_only=True):
        key, val = row[0], row[1]
        if key and val is not None:
            cfg[str(key).strip()] = str(val).strip()
    return cfg

# ─── Read a module sheet ───────────────────────────────────────────────────────
def read_module_sheet(wb, sheet_name):
    ws = wb[sheet_name]
    headers = [c.value for c in ws[3]]     # row 3 = column headers
    lessons = []
    for row in ws.iter_rows(min_row=5, values_only=True):  # row 4 = example, 5+ = data
        if row[0] is None or str(row[0]).strip() == "":
            continue
        record = {headers[i]: (row[i] if row[i] is not None else "") for i in range(len(headers))}
        lessons.append(record)
    return lessons

# ─── SQL helpers ───────────────────────────────────────────────────────────────
def sq(val):
    """Escape single quotes for PostgreSQL."""
    return str(val).replace("'", "''")

def new_uuid():
    return str(uuid.uuid4())

# ─── SQL template header / footer ─────────────────────────────────────────────
HEADER_TMPL = """\
-- =====================================================
-- Module {mod_num}: {mod_name} - Grade {grade} ({num_lessons} Lessons)
-- Learning Path: {learning_path_id}
-- Creator: {creator_id}
-- School: {school_id}
-- Training Module: {training_module_id}
-- Generated by generate_sql.py
-- =====================================================

DO $$
DECLARE
  v_custom_version_id UUID := '{custom_version_id}';
  v_learning_path_id UUID := '{learning_path_id}';
  v_lesson_id UUID;
BEGIN
  -- Create learning_path_version if it doesn't exist
  IF NOT EXISTS (SELECT 1 FROM bantrly.learning_path_version WHERE version_id = v_custom_version_id) THEN
    INSERT INTO bantrly.learning_path_version (
      version_id, learning_path_id, version_name, version_description,
      version_number, is_active, grade, section, created_on, created_by,
      created_by_role, is_custom, difficulty_level, school_id
    ) VALUES (
      v_custom_version_id, v_learning_path_id, '{version_name}',
      '{version_description}',
      (SELECT COALESCE(MAX(version_number), 0) + 1 FROM bantrly.learning_path_version WHERE learning_path_id = v_learning_path_id),
      true, {grade}, NULL, NOW(), '{creator_id}',
      '{creator_role}', true, '{difficulty_level}', '{school_id}'
    );
  END IF;
"""

FOOTER = "\nEND;\n$$ LANGUAGE plpgsql;\n"

# ─── Per-lesson SQL builders (one per module) ──────────────────────────────────

def lesson_block(cfg, l, mod_name, lesson_type, training_module_id, content_inserts, content_json, lesson_num):
    """Shared wrapper around lesson + lesson_content + lesson_version + sequence."""
    v_id_placeholder = "v_lesson_id"
    sort_order = l.get("sort_order", "")
    image_url  = sq(l.get("lesson_image_url", ""))
    l_name     = sq(l.get("lesson_name", f"Lesson {lesson_num}"))
    l_desc     = sq(l.get("lesson_description", ""))

    contents_json_str = json.dumps(content_json, ensure_ascii=False).replace("'", "''")

    version_content = {
        "lesson_name": l.get("lesson_name", ""),
        "lesson_description": l.get("lesson_description", ""),
        "training_module_id": training_module_id,
        "grade": int(cfg["grade"]),
        "section": None,
        "difficulty_level": cfg["difficulty_level"],
        "lesson_type": lesson_type,
        "contents": content_json,
    }
    version_json = json.dumps(version_content, ensure_ascii=False).replace("'", "''")

    return f"""
  -- Lesson {lesson_num}: {l.get("lesson_name", "")}
  v_lesson_id := gen_random_uuid();

  INSERT INTO bantrly.lesson (
    lesson_id, lesson_name, lesson_description, training_module_id,
    difficulty_level, lesson_type, created_on, created_by,
    created_by_role, is_deleted, is_assessment, grade, section, lesson_image_url
  ) VALUES (
    v_lesson_id, '{l_name}', '{l_desc}', '{training_module_id}',
    '{cfg["difficulty_level"]}',
    '{lesson_type}', NOW(), '{cfg["creator_id"]}',
    '{cfg["creator_role"]}', false, false, {cfg["grade"]}, NULL, '{image_url}'
  );

  INSERT INTO bantrly.lesson_content (content_id, lesson_id, content_key, content_value, created_at, updated_at) VALUES
{content_inserts};

  INSERT INTO bantrly.lesson_version_new (
    lesson_version_id, lesson_id, version_number, title, content, status, is_latest, created_at
  ) VALUES (
    gen_random_uuid(), v_lesson_id, 1, '{l_name}',
    '{version_json}',
    'published', true, NOW()
  );

  INSERT INTO bantrly.program_lesson_sequence_new (
    learning_path_id, version_id, school_id, lesson_id,
    lesson_type, grade, section, difficulty_level, sort_order
  ) VALUES (
    v_learning_path_id, v_custom_version_id, '{cfg["school_id"]}', v_lesson_id,
    '{lesson_type}', {cfg["grade"]}, NULL, '{cfg["difficulty_level"]}', {sort_order}
  );
"""

def ci(lesson_id_var, key, val):
    """Single lesson_content insert row."""
    return f"    (gen_random_uuid(), {lesson_id_var}, '{sq(key)}', '{sq(str(val))}', NOW(), NOW())"


"""
generate_sql.py
────────────────────────────────────────────────────────────────
Reads lesson_template.xlsx and generates SQL files for any or all
of the 8 modules.

Usage:
    python generate_sql.py              # generates ALL 8 modules
    python generate_sql.py 1 3 5        # generates modules 1, 3 and 5 only
    python generate_sql.py --list       # show module names and exit

Output files:  module_1_output.sql … module_8_output.sql
"""

import sys

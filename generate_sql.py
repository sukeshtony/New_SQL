# ─── Wrap header + blocks + footer ────────────────────────────────────────────
def _wrap(cfg, mod_num, mod_name, training_id, blocks, num_lessons):
    header = HEADER_TMPL.format(
        mod_num=mod_num,
        mod_name=mod_name,
        grade=cfg["grade"],
        num_lessons=num_lessons,
        learning_path_id=cfg["learning_path_id"],
        creator_id=cfg["creator_id"],
        school_id=cfg["school_id"],
        training_module_id=training_id,
        custom_version_id=cfg["custom_version_id"],
        version_name=sq(cfg["version_name"]),
        version_description=sq(cfg["version_description"]),
        creator_role=cfg["creator_role"],
        difficulty_level=cfg["difficulty_level"],
    )
    return header + "".join(blocks) + FOOTER


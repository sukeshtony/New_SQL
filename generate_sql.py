# ─── Main ─────────────────────────────────────────────────────────────────────
def main():
    args = sys.argv[1:]

    if "--list" in args:
        for num, (name, _) in MODULES.items():
            print(f"  Module {num}: {name}")
        return

    # Determine which modules to generate
    if args:
        try:
            selected = [int(a) for a in args]
        except ValueError:
            sys.exit("❌  Pass module numbers (1–8) or --list")
        for n in selected:
            if n not in MODULES:
                sys.exit(f"❌  Module {n} does not exist. Valid: 1–8")
    else:
        selected = list(MODULES.keys())

    wb  = load_wb()
    cfg = read_common(wb)

    for mod_num in selected:
        name, builder = MODULES[mod_num]
        print(f"⏳  Generating Module {mod_num}: {name} …")
        try:
            sql = builder(wb, cfg)
        except Exception as e:
            print(f"  ❌  Error: {e}")
            continue
        out_path = Path(f"module_{mod_num}_output.sql")
        out_path.write_text(sql, encoding="utf-8")
        print(f"  ✅  Saved → {out_path}  ({len(sql):,} chars)")

    print("\nDone.")

if __name__ == "__main__":
    main()
